-- NETFLIX SQL ANALYSIS
-- Business Insights:
-- Key findings from the Netflix Movies and TV Shows analysis
-- ---------------------------------------------------------------------------------------------

-- Insight 1:
-- Netflix's catalog is Movie-heavy, with Movies accounting for 69.62% of the total catalog
-- compared with 30.38% TV Shows.
-- ----------------------------------------------------------------------------------------------

-- Insight 2:
-- TV Shows became an increasingly significant part of Netflix's yearly additions over time.
-- In 2021, TV Shows represented 33.71% of titles added to the catalog.
-- ----------------------------------------------------------------------------------------------

-- Insight 3:
-- 2019 recorded the highest number of Movie additions (1,424), while 2020 recorded the
-- highest number of TV Show additions (595) in the dataset.
-- ----------------------------------------------------------------------------------------------

-- Insight 4:
-- TV Shows were added to Netflix closer to their original release year on average.
-- The average release-to-addition gap was approximately 2.30 years for TV Shows,
-- compared with approximately 5.73 years for Movies.
-- ---------------------------------------------------------------------------------------------

-- Insight 5:
-- International Movies and International TV Shows were the most common genre associations
-- within their respective content types, with 2,752 International Movie associations and
-- 1,351 International TV Show associations.
-- ---------------------------------------------------------------------------------------------

-- Insight 6:
-- Older Movies have a larger presence in the dataset than older TV Shows.
-- 19.44% of Movies were added to Netflix at least 10 years after their original release,
-- compared with 5.55% of TV Shows.
-- ---------------------------------------------------------------------------------------------

-- Insight 7:
-- Among the top 10 directors by title associations, the catalog is overwhelmingly
-- Movie-focused. Nine of the top 10 directors had only Movie associations in this dataset,
-- while Marcus Raboy had 15 Movies and 1 TV Show.
